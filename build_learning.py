# Builds learning_items.js from learning_statements.md (the source of truth).
# Rerun after editing the markdown:  python3 build_learning.py

import json
import re

DOMAINS = {'E': 'environment', 'H': 'health', 'A': 'animal_welfare'}

md = open('learning_statements.md', encoding='utf-8').read()


def html(text):
    """markdown *italics* -> <i>italics</i>"""
    return re.sub(r'\*(.+?)\*', r'<i>\1</i>', text.strip())


items = []
for m in re.finditer(r'^\*\*([EHA])(\d+)\.\*\* (.+)\n((?:- .*\n?)+)', md, re.M):
    letter, num, statement, fields = m.groups()
    answer = re.search(r'^- Answer: (\w+)', fields, re.M).group(1).lower()
    source = re.search(r'^- Feedback source: (.+)$', fields, re.M).group(1)
    items.append({
        'item': f'{letter}{num}',
        'domain': DOMAINS[letter],
        'statement': html(statement),
        'accurate': answer == 'accurate',
        'source': html(source),
    })

counts = {(d, a): sum(i['domain'] == d and i['accurate'] == a for i in items)
          for d in DOMAINS.values() for a in (True, False)}
print(f'{len(items)} items; per domain x accurate: {counts}')

with open('learning_items.js', 'w', encoding='utf-8') as f:
    f.write('// GENERATED by build_learning.py from learning_statements.md -- edit the markdown, not this file\n')
    f.write('var learning_items = ' + json.dumps(items, indent=2, ensure_ascii=False) + ';\n')
